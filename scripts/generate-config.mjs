// Generates compile-time Angular config and Cloudflare Pages redirects from
// the BACKEND_URL environment variable (e.g. https://123-456-789-10.sslip.io).
// No secrets are stored in the repository.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const raw = (process.env.BACKEND_URL || '').trim().replace(/\/+$/, '');

if (!raw) {
  console.warn('BACKEND_URL is not set - keeping committed environment.prod.ts defaults.');
  process.exit(0);
}

if (!/^https?:\/\//.test(raw)) {
  console.error('BACKEND_URL must start with https:// (or http:// for local testing).');
  process.exit(1);
}

const apiUrl = `${raw}/api`;
const wsUrl = raw.startsWith('https://')
  ? `${raw}/api/ws`
  : `${raw}/api/ws`;

const envFile = `// Generated by scripts/generate-config.mjs - do not edit by hand.
export const environment = {
  production: true,
  apiUrl: '${apiUrl}',
  wsUrl: '${wsUrl}',
  tokenKey: 'access_token',
  refreshKey: 'refresh_token',
};
`;

writeFileSync(resolve(root, 'src/environments/environment.prod.ts'), envFile, 'utf8');

mkdirSync(resolve(root, 'public'), { recursive: true });
const redirects = `# Generated by scripts/generate-config.mjs
/api/*  ${apiUrl}/:splat  200
/*      /index.html       200
`;
writeFileSync(resolve(root, 'public/_redirects'), redirects, 'utf8');

console.log(`Generated apiUrl=${apiUrl}`);
console.log(`Generated wsUrl=${wsUrl}`);
